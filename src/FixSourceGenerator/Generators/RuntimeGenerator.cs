    /// <summary>
    /// Caller-owned metadata for generated scoped writers. Initialize the complete span once with
    /// <see cref=""Initialize""/> before its first use. A completed or failed state may be acquired
    /// again without reinitialization; its generation is advanced so old handles stay stale.
    /// </summary>
    public struct FixWriterState
    {
        private const int Initialized = unchecked((int)0x46575331);

        internal int Marker;
        internal int Status;
        internal long Generation;
        internal int ExpectedCount;
        internal int ActualCount;
        internal int EntryActive;
        internal int DelimiterTag;
        internal int DelimiterWritten;

        public static void Initialize(Span<FixWriterState> state)
        {
            if (state.IsEmpty)
            {
                throw new ArgumentException(""Writer state must not be empty."", nameof(state));
            }

            if (state[0].Marker == Initialized)
            {
                for (int i = 1; i < state.Length; i++)
                {
                    if (state[i].Marker != Initialized)
                    {
                        throw new ArgumentException(""Writer state is only partially initialized."", nameof(state));
                    }
                }
                if (state[0].Status == 1)
                {
                    throw new InvalidOperationException(""The writer state is already owned by a live message."");
                }
                return;
            }

            state.Clear();
            for (int i = 0; i < state.Length; i++)
            {
                state[i].Marker = Initialized;
            }
        }

        internal static bool IsInitialized(in FixWriterState state) => state.Marker == Initialized;
    }

    /// <summary>
    /// Shared engine used by generated scoped handles. The destination and state are caller-owned
    /// and must remain alive, non-overlapping and exclusive until the message is finished.
    /// </summary>
    public ref struct FixWriterContext
    {
        private Span<FixWriterState> _state;
        private FixSpanWriter _writer;
        private long _generation;
        private int _groupDepth;

        public static FixWriterContext Begin(
            Span<byte> destination,
            Span<FixWriterState> state,
            int requiredStateLength,
            scoped ReadOnlySpan<byte> beginString,
            scoped ReadOnlySpan<byte> msgType)
        {
            if (requiredStateLength < 1 || state.Length < requiredStateLength)
            {
                throw new ArgumentException(""The writer state span is too small for this message."", nameof(state));
            }

            state = state.Slice(0, requiredStateLength);
            if (destination.Overlaps(MemoryMarshal.AsBytes(state)))
            {
                throw new ArgumentException(""Writer state must not overlap the FIX destination."", nameof(state));
            }

            for (int i = 0; i < state.Length; i++)
            {
                if (!FixWriterState.IsInitialized(in state[i]))
                {
                    throw new ArgumentException(""Initialize the writer state before its first use."", nameof(state));
                }
            }

            ref FixWriterState root = ref state[0];
            if (root.Status == 1)
            {
                throw new InvalidOperationException(""The writer state is already owned by a live message."");
            }
            if (root.Generation == long.MaxValue)
            {
                throw new InvalidOperationException(""The writer state generation is exhausted."");
            }

            for (int i = 1; i < state.Length; i++)
            {
                state[i].Status = 0;
                state[i].ExpectedCount = 0;
                state[i].ActualCount = 0;
                state[i].EntryActive = 0;
                state[i].DelimiterTag = 0;
                state[i].DelimiterWritten = 0;
            }

            root.Status = 1;
            root.Generation++;
            var context = new FixWriterContext
            {
                _state = state,
                _writer = new FixSpanWriter(destination),
                _generation = root.Generation,
                _groupDepth = 0,
            };

            try
            {
                context._writer.BeginMessage(beginString, msgType);
                return context;
            }
            catch (ArgumentException)
            {
                context.PoisonCore();
                throw;
            }
            catch (InvalidOperationException)
            {
                context.PoisonCore();
                throw;
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public readonly void Validate()
        {
            if (_state.IsEmpty ||
                _generation == 0 ||
                _state[0].Status != 1 ||
                _state[0].Generation != _generation)
            {
                ThrowInvalidHandle();
            }
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        private static void ThrowInvalidHandle() =>
            throw new InvalidOperationException(""The writer handle is default, stale, completed, or failed."");

        public void Poison()
        {
            Validate();
            PoisonCore();
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal void ValidateOrder(int currentOrder, int nextOrder)
        {
            if (currentOrder >= nextOrder)
            {
                // Successful paths validate in the following mutation; rejection must not poison a stale owner.
                Validate();
                ThrowInvalidOrder();
            }
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        private void ThrowInvalidOrder()
        {
            PoisonCore();
            throw new InvalidOperationException(""A field or scope cannot be emitted twice or out of schema order."");
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal void ValidateText(scoped ReadOnlySpan<byte> value, string fieldName, string parameterName)
        {
            if (value.IsEmpty)
            {
                Validate();
                ThrowEmptyText(fieldName, parameterName);
            }
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        private void ThrowEmptyText(string fieldName, string parameterName)
        {
            PoisonCore();
            throw new ArgumentException(""An explicit "" + fieldName + "" value must not be empty."", parameterName);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal void ValidateCode(bool isValid, string parameterName)
        {
            if (!isValid)
            {
                Validate();
                ThrowInvalidCode(parameterName);
            }
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        private void ThrowInvalidCode(string parameterName)
        {
            PoisonCore();
            throw new ArgumentOutOfRangeException(parameterName);
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, scoped ReadOnlySpan<byte> value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, int value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, long value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, long mantissa, int scale)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, mantissa, scale);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, decimal value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        public void WriteField(scoped ReadOnlySpan<byte> prefix, FixDecimal value)
        {
            if (!value.HasValidScale)
            {
                Validate();
                PoisonCore();
                throw new ArgumentOutOfRangeException(""scale"", ""Scale must be between 0 and 18."");
            }
            if (value.IsScaled)
            {
                WriteField(prefix, value.Mantissa, value.Scale);
            }
            else
            {
                WriteField(prefix, value.Decimal);
            }
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, bool value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, char value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, DateTime value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, DateOnly value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void WriteField(scoped ReadOnlySpan<byte> prefix, TimeOnly value)
        {
            PrepareMutation();
            ValidateEntryDelimiter(prefix);
            _writer.WriteField(prefix, value);
            _state[0].Status = 1;
        }

        public FixWriterContext Transfer()
        {
            Renew();
            return Take();
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        internal FixWriterContext Take()
        {
            var next = this;
            _generation = 0;
            return next;
        }

        public void BeginGroup(scoped ReadOnlySpan<byte> prefix, int expectedCount)
        {
            Validate();
            if (expectedCount < 0)
            {
                PoisonCore();
                throw new ArgumentOutOfRangeException(nameof(expectedCount));
            }
            if (_groupDepth + 1 >= _state.Length)
            {
                PoisonCore();
                throw new InvalidOperationException(""The generated writer state is too small for the group nesting depth."");
            }

            WriteField(prefix, expectedCount);
            _groupDepth++;
            ref FixWriterState frame = ref _state[_groupDepth];
            frame.Status = 1;
            frame.ExpectedCount = expectedCount;
            frame.ActualCount = 0;
            frame.EntryActive = 0;
        }

        public void BeginEntry(int delimiterTag)
        {
            Validate();
            ref FixWriterState frame = ref CurrentGroup();
            if (frame.EntryActive != 0 || frame.ActualCount >= frame.ExpectedCount)
            {
                PoisonCore();
                throw new InvalidOperationException(""A group entry is already active or exceeds expectedCount."");
            }

            EnsureCanRenew();
            frame.EntryActive = 1;
            frame.DelimiterTag = delimiterTag;
            frame.DelimiterWritten = 0;
            RenewCore();
        }

        public void EndEntry()
        {
            Validate();
            ref FixWriterState frame = ref CurrentGroup();
            if (frame.EntryActive == 0 || frame.DelimiterWritten == 0)
            {
                PoisonCore();
                throw new InvalidOperationException(""No group entry is active or its delimiter was not written first."");
            }

            EnsureCanRenew();
            frame.EntryActive = 0;
            frame.DelimiterTag = 0;
            frame.DelimiterWritten = 0;
            frame.ActualCount++;
            RenewCore();
        }

        public void EndGroup()
        {
            Validate();
            ref FixWriterState frame = ref CurrentGroup();
            if (frame.EntryActive != 0 || frame.ActualCount != frame.ExpectedCount)
            {
                PoisonCore();
                throw new InvalidOperationException(""The number of completed group entries does not match expectedCount."");
            }

            EnsureCanRenew();
            frame.Status = 0;
            frame.ExpectedCount = 0;
            frame.ActualCount = 0;
            _groupDepth--;
            RenewCore();
        }

        public int Finish()
        {
            Validate();
            if (_groupDepth != 0)
            {
                PoisonCore();
                throw new InvalidOperationException(""A child group is still active."");
            }

            EnsureCanRenew();
            try
            {
                int length = _writer.Finish();
                _state[0].Status = 2;
                RenewCore();
                _generation = 0;
                return length;
            }
            catch (ArgumentException)
            {
                PoisonCore();
                throw;
            }
            catch (InvalidOperationException)
            {
                PoisonCore();
                throw;
            }
        }

        private ref FixWriterState CurrentGroup()
        {
            if (_groupDepth == 0 || _state[_groupDepth].Status != 1)
            {
                PoisonCore();
                throw new InvalidOperationException(""No group scope is active."");
            }

            return ref _state[_groupDepth];
        }

        private void PrepareMutation()
        {
            Validate();
            EnsureCanRenew();
            // A write is committed only on normal return; any exception leaves every handle poisoned.
            _state[0].Status = -1;
            RenewCore();
        }

        private void ValidateEntryDelimiter(scoped ReadOnlySpan<byte> prefix)
        {
            if (_groupDepth == 0)
            {
                return;
            }

            ref FixWriterState frame = ref _state[_groupDepth];
            if (frame.EntryActive == 0 || frame.DelimiterWritten != 0)
            {
                return;
            }

            int tag = 0;
            int index = 0;
            while (index < prefix.Length && prefix[index] >= (byte)'0' && prefix[index] <= (byte)'9')
            {
                tag = checked(tag * 10 + prefix[index] - (byte)'0');
                index++;
            }
            if (index == 0 || index >= prefix.Length || prefix[index] != (byte)'=' || tag != frame.DelimiterTag)
            {
                PoisonCore();
                throw new InvalidOperationException(""The first field of a group entry must be its structural delimiter."");
            }

            frame.DelimiterWritten = 1;
        }

        private void Renew()
        {
            Validate();
            EnsureCanRenew();
            RenewCore();
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        private void EnsureCanRenew()
        {
            if (_state[0].Generation == long.MaxValue)
            {
                ThrowGenerationExhausted();
            }
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        private void ThrowGenerationExhausted()
        {
            _state[0].Status = -1;
            _generation = 0;
            throw new InvalidOperationException(""The writer state generation is exhausted."");
        }

        private void RenewCore()
        {
            _state[0].Generation++;
            _generation = _state[0].Generation;
        }

        private void PoisonCore()
        {
            if (!_state.IsEmpty)
            {
                _state[0].Status = -1;
                if (_state[0].Generation != long.MaxValue)
                {
                    _state[0].Generation++;
                }
            }
            _generation = 0;
        }
    }

    /// <summary>
    /// Forward-only, allocation-free scanner over a FIX tag=value byte buffer. Exposes both an
    /// instance forward cursor and static random-access helpers used by generated readers.
    /// </summary>
    public ref struct FixSpanReader
    {
        private const byte Soh = 0x01;

        private readonly ReadOnlySpan<byte> _buffer;
        private int _position;

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public FixSpanReader(ReadOnlySpan<byte> buffer)
        {
            _buffer = buffer;
            _position = 0;
        }

        /// <summary>Resets the forward cursor to the start of the buffer.</summary>
        public void Reset() => _position = 0;

        /// <summary>
        /// Advances the forward cursor to the next <c>tag=value</c> field, returning its tag and
        /// value span. Returns false at end of buffer.
        /// </summary>
        public bool TryReadNext(out int tag, out ReadOnlySpan<byte> value)
        {
            if (TryReadField(_buffer, _position, out tag, out int valueStart, out int valueLength, out int nextPos))
            {
                value = _buffer.Slice(valueStart, valueLength);
                _position = nextPos;
                return true;
            }

            value = default;
            return false;
        }

        /// <summary>
        /// Scans the whole buffer for the first occurrence of <paramref name=""tag""/>, returning
        /// its value span without allocating.
        /// </summary>
        public readonly bool TryGetField(int tag, out ReadOnlySpan<byte> value) => TryGetField(_buffer, tag, out value);

        /// <summary>Low-level field parser: reads <c>tag=value&lt;SOH&gt;</c> starting at <paramref name=""pos""/>.</summary>
        public static bool TryReadField(ReadOnlySpan<byte> buffer, int pos, out int tag, out int valueStart, out int valueLength, out int nextPos)
        {
            tag = 0;
            valueStart = 0;
            valueLength = 0;
            nextPos = pos;

            int length = buffer.Length;
            if (pos >= length)
            {
                return false;
            }

            int i = pos;
            int parsedTag = 0;
            bool sawDigit = false;
            while (i < length && buffer[i] != (byte)'=')
            {
                byte c = buffer[i];
                if (c >= (byte)'0' && c <= (byte)'9')
                {
                    parsedTag = (parsedTag * 10) + (c - (byte)'0');
                    sawDigit = true;
                }
                i++;
            }

            if (i >= length || !sawDigit)
            {
                return false;
            }

            i++; // skip '='
            int vStart = i;
            while (i < length && buffer[i] != Soh)
            {
                i++;
            }

            tag = parsedTag;
            valueStart = vStart;
            valueLength = i - vStart;
            nextPos = (i < length) ? i + 1 : i;
            return true;
        }

        public static bool TryGetField(ReadOnlySpan<byte> buffer, int tag, out ReadOnlySpan<byte> value)
        {
            int pos = 0;
            while (TryReadField(buffer, pos, out int t, out int valueStart, out int valueLength, out int nextPos))
            {
                if (t == tag)
                {
                    value = buffer.Slice(valueStart, valueLength);
                    return true;
                }

                pos = nextPos;
            }

            value = default;
            return false;
        }

        public static ReadOnlySpan<byte> GetField(ReadOnlySpan<byte> buffer, int tag)
            => TryGetField(buffer, tag, out var value) ? value : default;

        // --- Pure value-parsing helpers (no tag lookup) -----------------------------------
        // Used by generated readers, which locate each field's (start, length) via a single
        // forward scan in the constructor (docs/CONTRACT.md §2 ""scan único, parse sob
        // demanda""), then parse the already-located span lazily on property access via these
        // helpers. Kept separate from the buffer+tag lookup helpers below (still used e.g. by
        // {Group}GroupReader.Count, which reads a single counter field without needing a full
        // per-entry scan).

        public static bool TryParseInt(ReadOnlySpan<byte> value, out int result)
            => Utf8Parser.TryParse(value, out result, out _);

        public static int ParseInt(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseInt(value, out int result);
            Debug.Assert(ok, ""required INT field is absent or malformed"");
            return result;
        }

        public static bool TryParseDecimal(ReadOnlySpan<byte> value, out decimal result)
            => Utf8Parser.TryParse(value, out result, out _);

        public static decimal ParseDecimal(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseDecimal(value, out decimal result);
            Debug.Assert(ok, ""required decimal field is absent or malformed"");
            return result;
        }

        public static bool TryParseBool(ReadOnlySpan<byte> value, out bool result)
        {
            if (value.Length > 0)
            {
                result = value[0] == (byte)'Y';
                return true;
            }

            result = false;
            return false;
        }

        public static bool ParseBool(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseBool(value, out bool result);
            Debug.Assert(ok, ""required BOOLEAN field is absent or malformed"");
            return result;
        }

        public static bool TryParseByte(ReadOnlySpan<byte> value, out byte result)
        {
            if (value.Length > 0)
            {
                result = value[0];
                return true;
            }

            result = 0;
            return false;
        }

        public static byte ParseByte(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseByte(value, out byte result);
            Debug.Assert(ok, ""required CHAR field is absent or malformed"");
            return result;
        }

        public static bool TryParseDateTime(ReadOnlySpan<byte> value, out DateTime result)
        {
            if ((value.Length == 17 || value.Length == 21) && value[8] == (byte)'-'
                && TryReadDateParts(value.Slice(0, 8), out int year, out int month, out int day)
                && TryReadTimeParts(value.Slice(9), out int hour, out int minute, out int second, out int millisecond))
            {
                result = new DateTime(year, month, day, hour, minute, second, millisecond, DateTimeKind.Utc);
                return true;
            }

            if (value.Length > 0)
            {
                Span<char> chars = stackalloc char[value.Length];
                for (int i = 0; i < value.Length; i++)
                {
                    chars[i] = (char)value[i];
                }

                return DateTime.TryParseExact(
                    chars,
                    _timestampFormats,
                    CultureInfo.InvariantCulture,
                    DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal,
                    out result);
            }

            result = default;
            return false;
        }

        public static DateTime ParseDateTime(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseDateTime(value, out DateTime result);
            Debug.Assert(ok, ""required timestamp field is absent or malformed"");
            return result;
        }

        public static bool TryParseDateOnly(ReadOnlySpan<byte> value, out DateOnly result)
        {
            if (TryReadDateParts(value, out int year, out int month, out int day))
            {
                result = new DateOnly(year, month, day);
                return true;
            }

            if (value.Length > 0)
            {
                Span<char> chars = stackalloc char[value.Length];
                for (int i = 0; i < value.Length; i++)
                {
                    chars[i] = (char)value[i];
                }

                return DateOnly.TryParseExact(chars, ""yyyyMMdd"", CultureInfo.InvariantCulture, DateTimeStyles.None, out result);
            }

            result = default;
            return false;
        }

        public static DateOnly ParseDateOnly(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseDateOnly(value, out DateOnly result);
            Debug.Assert(ok, ""required date field is absent or malformed"");
            return result;
        }

        public static bool TryParseTimeOnly(ReadOnlySpan<byte> value, out TimeOnly result)
        {
            if (TryReadTimeParts(value, out int hour, out int minute, out int second, out int millisecond))
            {
                result = new TimeOnly(hour, minute, second, millisecond);
                return true;
            }

            if (value.Length > 0)
            {
                Span<char> chars = stackalloc char[value.Length];
                for (int i = 0; i < value.Length; i++)
                {
                    chars[i] = (char)value[i];
                }

                return TimeOnly.TryParseExact(chars, _timeFormats, CultureInfo.InvariantCulture, DateTimeStyles.None, out result);
            }

            result = default;
            return false;
        }

        public static TimeOnly ParseTimeOnly(ReadOnlySpan<byte> value)
        {
            bool ok = TryParseTimeOnly(value, out TimeOnly result);
            Debug.Assert(ok, ""required time field is absent or malformed"");
            return result;
        }

        private static bool TryReadDateParts(ReadOnlySpan<byte> value, out int year, out int month, out int day)
        {
            year = month = day = 0;
            return value.Length == 8
                && TryReadDigits(value, 0, 4, out year)
                && TryReadDigits(value, 4, 2, out month)
                && TryReadDigits(value, 6, 2, out day)
                && year >= 1 && month >= 1 && month <= 12
                && day >= 1 && day <= DateTime.DaysInMonth(year, month);
        }

        private static bool TryReadTimeParts(ReadOnlySpan<byte> value, out int hour, out int minute,
            out int second, out int millisecond)
        {
            hour = minute = second = millisecond = 0;
            return (value.Length == 8 || value.Length == 12)
                && value[2] == (byte)':' && value[5] == (byte)':'
                && TryReadDigits(value, 0, 2, out hour)
                && TryReadDigits(value, 3, 2, out minute)
                && TryReadDigits(value, 6, 2, out second)
                && hour <= 23 && minute <= 59 && second <= 59
                && (value.Length == 8 || (value[8] == (byte)'.'
                    && TryReadDigits(value, 9, 3, out millisecond)));
        }

        private static bool TryReadDigits(ReadOnlySpan<byte> value, int start, int length, out int result)
        {
            result = 0;
            for (int i = start; i < start + length; i++)
            {
                uint digit = (uint)(value[i] - (byte)'0');
                if (digit > 9)
                {
                    return false;
                }

                result = result * 10 + (int)digit;
            }

            return true;
        }

