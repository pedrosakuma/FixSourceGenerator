    internal static class RuntimeGenerator
    {
        public static IEnumerable<(string hintName, string content)> Generate(string @namespace, GenerationContext context)
        {
            if (!context.GeneratedRuntimeNamespaces.Add(@namespace))
            {
                yield break;
            }

            yield return ($"{@namespace}.Runtime.FixRuntime.g.cs", Template.Replace("__NS__", @namespace));
        }

