    /// <summary>
    /// Emits the shared, allocation-minimal runtime helpers (<c>FixSpanReader</c>,
    /// <c>FixSpanWriter</c>, <c>FixGroupEnumerator</c>) into <c>{ns}.Runtime</c>, once per namespace
    /// (deduped via <see cref="GenerationContext.GeneratedRuntimeNamespaces"/>). The helpers are
    /// embedded as a C# source template, mirroring the SbeSourceGenerator SpanReader/SpanWriter
